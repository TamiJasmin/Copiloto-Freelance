-- ============================================================
-- RPC: resumen del Dashboard (1 sola llamada, sin traer filas)
-- ============================================================
create or replace function public.dashboard_summary(p_month date default null)
returns table (
  quoted     numeric,
  collected  numeric,
  pending    numeric,
  open_count int
)
language sql stable security invoker as $$
  with m as (
    select date_trunc('month', coalesce(p_month, current_date)) as start
  )
  select
    coalesce(sum(q.total_amount) filter (
      where q.created_at >= m.start and q.created_at < m.start + interval '1 month'
    ), 0) as quoted,
    coalesce(sum(q.total_amount) filter (
      where q.status = 'cobrado'
        and q.paid_at >= m.start and q.paid_at < m.start + interval '1 month'
    ), 0) as collected,
    coalesce(sum(q.total_amount) filter (
      where q.status in ('enviado', 'aprobado')
    ), 0) as pending,
    count(*) filter (where q.status in ('borrador', 'enviado', 'aprobado'))::int as open_count
  from public.quotes q, m
  where q.user_id = auth.uid();
$$;

-- ============================================================
-- Vista de conveniencia: presupuesto + nombre/wpp del cliente
-- ============================================================
create or replace view public.quotes_with_client
with (security_invoker = true) as
select
  q.*,
  c.name            as client_name,
  c.whatsapp_number as client_whatsapp
from public.quotes q
join public.clients c on c.id = q.client_id;

